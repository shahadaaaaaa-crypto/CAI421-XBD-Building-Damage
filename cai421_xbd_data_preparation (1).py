# Cell 25: Training and Evaluation Functions

criterion = nn.CrossEntropyLoss()


def train_one_epoch(model, loader, optimizer, model_type):

    model.train()

    total_loss = 0.0
    all_predictions = []
    all_labels = []

    for pre_images, post_images, labels in loader:

        pre_images = pre_images.to(DEVICE)
        post_images = post_images.to(DEVICE)
        labels = labels.to(DEVICE)

        optimizer.zero_grad()

        if model_type == "baseline":
            outputs = model(post_images)
        else:
            outputs = model(pre_images, post_images)

        loss = criterion(outputs, labels)

        loss.backward()
        optimizer.step()

        total_loss += loss.item()

        predictions = torch.argmax(outputs, dim=1)

        all_predictions.extend(
            predictions.detach().cpu().numpy()
        )

        all_labels.extend(
            labels.detach().cpu().numpy()
        )

    epoch_loss = total_loss / max(len(loader), 1)

    epoch_accuracy = accuracy_score(
        all_labels, all_predictions
    )

    return epoch_loss, epoch_accuracy


def evaluate_model(model, loader, model_type):

    model.eval()

    all_predictions = []
    all_labels = []

    total_loss = 0.0

    with torch.no_grad():

        for pre_images, post_images, labels in loader:

            pre_images = pre_images.to(DEVICE)
            post_images = post_images.to(DEVICE)
            labels = labels.to(DEVICE)

            if model_type == "baseline":
                outputs = model(post_images)
            else:
                outputs = model(pre_images, post_images)

            loss = criterion(outputs, labels)
            total_loss += loss.item()

            predictions = torch.argmax(outputs, dim=1)

            all_predictions.extend(
                predictions.cpu().numpy()
            )

            all_labels.extend(
                labels.cpu().numpy()
            )

    results = {
        "loss": total_loss / max(len(loader), 1),
        "accuracy": accuracy_score(
            all_labels, all_predictions
        ),
        "precision_macro": precision_score(
            all_labels, all_predictions,
            average="macro", zero_division=0
        ),
        "recall_macro": recall_score(
            all_labels, all_predictions,
            average="macro", zero_division=0
        ),
        "f1_macro": f1_score(
            all_labels, all_predictions,
            average="macro", zero_division=0
        ),
        "f1_weighted": f1_score(
            all_labels, all_predictions,
            average="weighted", zero_division=0
        )
    }

    return results, all_labels, all_predictions


