# Cell 24: ResNet-50 and Siamese ResNet-50

def create_resnet50_backbone():
    try:
        backbone = models.resnet50(
            weights=models.ResNet50_Weights.DEFAULT
        )
        print("ResNet-50 pretrained weights loaded.")

    except Exception as e:
        print("Pretrained weights unavailable:", e)
        print("Using ResNet-50 with random initialization.")

        backbone = models.resnet50(weights=None)

    feature_dim = backbone.fc.in_features
    backbone.fc = nn.Identity()

    return backbone, feature_dim


# Baseline: Single-input ResNet-50
class BaselineResNet50(nn.Module):

    def __init__(self, num_classes=4):
        super().__init__()

        self.backbone, feature_dim = create_resnet50_backbone()

        self.classifier = nn.Sequential(
            nn.Dropout(0.3),
            nn.Linear(feature_dim, num_classes)
        )

    def forward(self, x):
        features = self.backbone(x)
        return self.classifier(features)


# Proposed Model: Siamese ResNet-50
class SiameseResNet50(nn.Module):

    def __init__(self, num_classes=4):
        super().__init__()

        self.backbone, feature_dim = create_resnet50_backbone()

        self.classifier = nn.Sequential(
            nn.Linear(feature_dim * 2, 512),
            nn.ReLU(),
            nn.Dropout(0.4),
            nn.Linear(512, num_classes)
        )

    def forward(self, pre_image, post_image):

        pre_features = self.backbone(pre_image)
        post_features = self.backbone(post_image)

        difference = torch.abs(
            pre_features - post_features
        )

        multiplication = (
            pre_features * post_features
        )

        fused_features = torch.cat(
            [difference, multiplication],
            dim=1
        )

        output = self.classifier(fused_features)

        return output


