CLASS_NAMES = [
    "no-damage",
    "minor-damage",
    "major-damage",
    "destroyed"
]

CLASS_TO_IDX = {
    name: idx for idx, name in enumerate(CLASS_NAMES)
}

IMAGE_SIZE = 224
BATCH_SIZE = 16

image_transform = transforms.Compose([
    transforms.Resize((IMAGE_SIZE, IMAGE_SIZE)),
    transforms.ToTensor(),
    transforms.Normalize(
        mean=[0.485, 0.456, 0.406],
        std=[0.229, 0.224, 0.225]
    )
])

class XBDPairDataset(Dataset):
    def __init__(self, dataframe, transform=None):
        self.dataframe = dataframe.reset_index(drop=True)
        self.transform = transform

        unknown_labels = (
            set(self.dataframe["label"].unique())
            - set(CLASS_TO_IDX.keys())
        )

        if unknown_labels:
            raise ValueError(
                f"Unknown labels: {unknown_labels}"
            )

    def __len__(self):
        return len(self.dataframe)

    def __getitem__(self, index):
        row = self.dataframe.iloc[index]

        with Image.open(row["pre_image"]) as img:
            pre_image = img.convert("RGB")

        with Image.open(row["post_image"]) as img:
            post_image = img.convert("RGB")

        if self.transform:
            pre_image = self.transform(pre_image)
            post_image = self.transform(post_image)

        label = CLASS_TO_IDX[row["label"]]

        return pre_image, post_image, torch.tensor(
            label, dtype=torch.long
        )


