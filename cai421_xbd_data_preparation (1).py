"""## Cell 5 — Generate four degradation types

For each sample, create degraded versions of both pre- and post-disaster crops. Original images are not modified. The four methods are Gaussian noise, atmospheric-style blur, resolution reduction, and JPEG compression artifacts.
"""

import numpy as np
import pandas as pd
import albumentations as A
from PIL import Image

def apply_degradation(image, kind, seed_value):
    arr = np.array(image.convert("RGB"))

    if kind == "gaussian_noise":
        transform = A.GaussNoise(
            std_range=(18 / 255, 18 / 255),
            mean_range=(0, 0),
            p=1.0
        )

    elif kind == "atmospheric_blur":
        transform = A.GaussianBlur(
            blur_limit=(3, 5),
            sigma_limit=(0.5, 2.0),
            p=1.0
        )

    elif kind == "resolution_reduction":
        transform = A.Downscale(
            scale_range=(0.25, 0.25),
            interpolation_pair={
                "downscale": 1,
                "upscale": 1
            },
            p=1.0
        )

    elif kind == "compression_artifacts":
        transform = A.ImageCompression(
            quality_range=(20, 20),
            compression_type="jpeg",
            p=1.0
        )

    else:
        raise ValueError(f"Unknown degradation type: {kind}")

    pipeline = A.Compose([transform], seed=seed_value)
    result = pipeline(image=arr)["image"]

    return Image.fromarray(result)


