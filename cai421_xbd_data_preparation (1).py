"""## Cell 4 — Split into train, validation, and test

The split is grouped by `pair_id` so crops from the same satellite image pair cannot appear in more than one split. The target proportions are approximately 70% train, 15% validation, and 15% test. Exact counts depend on the selected image pairs.
"""

import pandas as pd
import numpy as np
from sklearn.model_selection import StratifiedGroupKFold
from pathlib import Path

SEED = 42

data_dir = Path("/content/drive/MyDrive/CAI421_Project/final_data")
manifest_path = data_dir / "building_manifest.csv"
output_path = data_dir / "building_manifest_with_splits.csv"

df = pd.read_csv(manifest_path)

# Identify the label column
label_candidates = [
    "label", "damage_label", "damage_class",
    "damage_type", "class"
]
label_col = next(
    (col for col in label_candidates if col in df.columns),
    None
)

if label_col is None:
    raise ValueError(
        f"Cannot identify the damage-label column. "
        f"Available columns: {df.columns.tolist()}"
    )

if "pair_id" not in df.columns:
    raise ValueError("The manifest must contain a pair_id column.")

# Generate group-aware folds
X = np.zeros(len(df))
y = df[label_col].astype(str)
groups = df["pair_id"]

outer_cv = StratifiedGroupKFold(
    n_splits=6, shuffle=True, random_state=SEED
)
outer_folds = list(outer_cv.split(X, y, groups))

# Search possible group-preserving train/validation/test splits
best_score = float("inf")
best_assignment = None

overall_dist = y.value_counts(normalize=True).sort_index()
target_ratios = {"train": 0.68, "validation": 0.15, "test": 0.17}

for test_fold, (remaining_idx, test_idx) in enumerate(outer_folds):
    remaining_df = df.iloc[remaining_idx].reset_index(drop=True)
    remaining_y = y.iloc[remaining_idx].reset_index(drop=True)
    remaining_groups = groups.iloc[remaining_idx].reset_index(drop=True)

    inner_cv = StratifiedGroupKFold(
        n_splits=5, shuffle=True, random_state=SEED
    )

    inner_folds = list(
        inner_cv.split(
            np.zeros(len(remaining_df)),
            remaining_y,
            remaining_groups
        )
    )

    for val_fold, (train_rel, val_rel) in enumerate(inner_folds):
        train_idx = remaining_idx[train_rel]
        val_idx = remaining_idx[val_rel]

        assignment = np.full(len(df), "", dtype=object)
        assignment[train_idx] = "train"
        assignment[val_idx] = "validation"
        assignment[test_idx] = "test"

        score = 0.0

        for split_name, target_ratio in target_ratios.items():
            split_idx = np.where(assignment == split_name)[0]
            split_y = y.iloc[split_idx]

            # Penalize split sizes that differ from the targets
            actual_ratio = len(split_idx) / len(df)
            score += 2 * abs(actual_ratio - target_ratio)

            # Encourage class proportions similar to the full dataset
            split_dist = (
                split_y.value_counts(normalize=True)
                .reindex(overall_dist.index, fill_value=0)
            )
            score += sum(
                abs(split_dist[c] - overall_dist[c])
                for c in overall_dist.index
            )

        if score < best_score:
            best_score = score
            best_assignment = assignment.copy()

if best_assignment is None:
    raise RuntimeError("Could not create a valid data split.")

df["split"] = best_assignment

# Verify that each image pair belongs to only one split
pair_split_counts = df.groupby("pair_id")["split"].nunique()
assert pair_split_counts.max() == 1, "Data leakage detected!"

