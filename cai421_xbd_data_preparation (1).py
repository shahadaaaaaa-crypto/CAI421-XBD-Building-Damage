# Cell 29: Robustness Evaluation Dataset

class XBDDegradedPairDataset(Dataset):

    def __init__(
        self,
        dataframe,
        degradation_type,
        transform=None
    ):

        self.dataframe = dataframe.reset_index(drop=True)
        self.degradation_type = degradation_type
        self.transform = transform

        self.degradation_dir = (
            PROJECT_DIR / "degraded_albumentations"
        )

        if degradation_type not in degradation_types:
            raise ValueError(
                f"Unknown degradation type: {degradation_type}"
            )

    def __len__(self):
        return len(self.dataframe)

    def __getitem__(self, index):

        row = self.dataframe.iloc[index]

        sample_id = str(row["sample_id"])

        pre_path = (
            self.degradation_dir
            / self.degradation_type
            / "pre"
            / f"{sample_id}.jpg"
        )

        post_path = (
            self.degradation_dir
            / self.degradation_type
            / "post"
            / f"{sample_id}.jpg"
        )

        if not pre_path.exists():
            raise FileNotFoundError(
                f"Missing degraded pre image: {pre_path}"
            )

        if not post_path.exists():
            raise FileNotFoundError(
                f"Missing degraded post image: {post_path}"
            )

        with Image.open(pre_path) as img:
            pre_image = img.convert("RGB")

        with Image.open(post_path) as img:
            post_image = img.convert("RGB")

        if self.transform:
            pre_image = self.transform(pre_image)
            post_image = self.transform(post_image)

        label = CLASS_TO_IDX[row["label"]]

        return (
            pre_image,
            post_image,
            torch.tensor(label, dtype=torch.long)
        )


